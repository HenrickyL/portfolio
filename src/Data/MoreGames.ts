import { GameMedia, GameProject } from "@/types/Game";

export const image = (src: string, alt: string): GameMedia => ({ kind: "image", src, alt });
export const video = (src: string, alt: string, poster?: string): GameMedia => ({ kind: "video", src, alt, poster });

